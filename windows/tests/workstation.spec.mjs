import { test, expect, _electron as electron } from '@playwright/test';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import os from 'node:os';

test('V7 workstation charts, account scope, saved research, simulation and CSV work in Electron', async () => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'edge-workstation-'));
  const options = process.env.JOURNAL_E2E_EXECUTABLE ? { executablePath: process.env.JOURNAL_E2E_EXECUTABLE, args: [] } : { args: ['.'] };
  const app = await electron.launch({ ...options, env: { ...process.env, JOURNAL_TEST_DATA_DIR: directory } });
  const page = await app.firstWindow();
  try {
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const nav = key => page.locator(`[data-view="${key}"]`).click();
    const button = name => page.getByRole('button', { name, exact: true });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await expect(page.locator('html')).toHaveClass(/no-motion/);
    await button('Örnek günlüğü keşfet').click();
    await expect(page.locator('#equity')).toBeVisible();
    await page.locator('.hero-chart').getByRole('button', { name: 'Önceki grafik noktası' }).click();
    await expect(page.locator('.hero-chart .plot-tooltip')).toContainText('$5.400,00');
    await page.screenshot({ path: 'test-results/v7-equity-selection.png' });
    await page.locator('[data-curve-mode="R"]').click();
    await expect(page.locator('.hero-chart output')).toContainText('+24,20R');
    await nav('Research');
    await page.getByLabel('İşlemlerde ara').fill('NQ');
    await expect(page.locator('main')).toContainText('n = 10');
    await page.getByLabel('Araştırmaya ad ver').fill('NQ testi');
    await button('Filtreyi kaydet').click();
    await expect(page.locator('[name="loadPreset"]')).toHaveValue(/.+/);
    await nav('Dashboard');
    await nav('Research');
    await expect(page.getByLabel('İşlemlerde ara')).toHaveValue('NQ');
    await expect(page.locator('#scatter-plot')).toBeVisible();
    await page.locator('[name="scatterID"]').selectOption({ index: 1 });
    await expect(button('İşleme git')).toBeVisible();
    await nav('Quant');
    await button('Senaryoları hesapla').click();
    await expect(page.locator('#simulation-chart')).toBeVisible({ timeout: 15000 });
    await page.locator('#simulation-chart').focus();
    await page.keyboard.press('ArrowLeft');
    await expect(page.locator('#simulation-chart').locator('..').locator('.plot-tooltip')).toContainText('%95');
    await page.screenshot({ path: 'test-results/v7-simulation.png', fullPage: true });
    await page.locator('.demo-banner button').click();
    await nav('Accounts');
    await button('Hesap ekle').click();
    await page.getByLabel('Hesap adı', { exact: true }).fill('EUR test');
    await page.locator('#account-form [name="currency"]').fill('EUR');
    await page.getByLabel('Kâr hedefi', { exact: true }).fill('1000');
    await button('Hesabı kaydet').click();
    await expect(page.locator('#account-picker option:checked')).toHaveText('EUR test');
    await expect(page.locator('main')).toContainText('Kâr hedefine ilerleme');
    await nav('Planning');
    await page.getByLabel('Piyasa senaryoları').fill('Seans planı');
    await button('Günlük planı kaydet').click();
    await expect(page.locator('#toast')).toHaveText('Plan kaydedildi.');
    await nav('CSV Aktarım');
    await page.locator('#mapped-csv').setInputFiles({ name: 'sample.csv', mimeType: 'text/csv', buffer: Buffer.from('date,instrument,gross_pnl,currency\n2026-10-01T10:00:00Z,NQ,125,EUR\n') });
    await button('Önizle').click();
    await expect(page.locator('main')).toContainText('1 işlem');
    await page.getByLabel('Önizlemeyi ve EUR para birimini onaylıyorum').check();
    await button('Yeni kayıtları aktar').click();
    await expect(page.locator('#toast')).toHaveText('CSV aktarımı tamamlandı.');
    await nav('Trades');
    await expect(page.locator('.trade-rows')).toContainText('€125,00');
    await page.locator('[data-trade]').click();
    await button('Gerçekleşmeler').click();
    await button('Madde ekle').click();
    await page.getByLabel('Kontrol maddesi').fill('Planı kontrol ettim');
    await page.getByLabel('Yanıt', { exact: true }).selectOption('true');
    await button('Gerçekleşmeleri kaydet').click();
    await expect(page.locator('#editor')).not.toBeVisible();
    const saved = await page.evaluate(() => window.journal.load());
    expect(saved.workspace.plans[0].scenarios).toBe('Seans planı');
    expect(saved.workspace.assignments[saved.trades[0].id]).toBe(saved.workspace.selectedAccountID);
    expect(saved.workspace.supplements[saved.trades[0].id].checklist[0].answer).toBe(true);
    const pdf = path.join(directory, 'report.pdf');
    await app.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, pdf);
    await button('PDF olarak kaydet').click();
    await expect(page.locator('#toast')).toHaveText('PDF kaydedildi.');
    expect((await fs.readFile(pdf)).subarray(0, 4).toString()).toBe('%PDF');
    expect(errors).toEqual([]);
  } catch (error) {
    console.error("Application status:", await page.locator("#toast").textContent());
    throw error;
  } finally {
    await app.close();
    await fs.rm(directory, { recursive: true, force: true });
  }
});
